package io.strimzi.operator.cluster.model.pki.cluster;

import java.io.File;
import java.lang.reflect.InvocationHandler;
import java.lang.reflect.Method;
import java.lang.reflect.Parameter;
import java.lang.reflect.Proxy;
import java.nio.file.Files;
import java.nio.file.StandardCopyOption;
import java.time.Clock;
import java.util.HashMap;
import java.util.Map;

import io.strimzi.certs.CertManager;
import io.strimzi.certs.OpenSslCertManager;

/**
 * Helper class for providing a mock CertManager impl driven from class path resources which returned know certificates in
 * a known order.
 * It comes in with a {@linkplain #record(String, Clock, File) "recording mode"} which writes the files generated by a real CertManager impl
 * and a {@linkplain #replay(String, File) "playback mode"} which just reads the files.
 * This is handy for tests which involve lots of complex interactions with a CertManager
 * and want to make assertions about e.g. the fingerprints of issued certs.
 * You'll probably need to use a TestClock or similar in the test so that the returned certificates don't go stale
 * and to guarantee complete repeatability.
 */
public class TestOpenSslCertManager {

    private static String baseName(Method method, Map<String, Integer> methodMap) {
        return String.format("%s-%d",
                method.getName(),
        //                Arrays.stream(method.getParameters())
        //                    .map(x -> x.getType().getName().hashCode())
        //                    .reduce(Integer::sum)
        //                        .get(),
                methodMap.compute(method.toString(), (k, v) -> v == null ? 0 : v + 1));
    }

    private static File argFile(Method method, String baseName, Parameter parameter, File dir) {
        return new File(dir, baseName + "." + parameter.getName());
    }

    public static CertManager record(String testName, Clock clock, File parentDir) {
        File testDir = new File(parentDir, testName);
        testDir.mkdirs();
        OpenSslCertManager delegate = new OpenSslCertManager(clock);
        Map<String, Integer> methodMap = new HashMap<>();
        return (CertManager) Proxy.newProxyInstance(CertManager.class.getClassLoader(), new Class[]{CertManager.class},
            (proxy, method, args) -> {
                // Record the input files
                Map<File, Long> mtimes = new HashMap<>();
                for (Object arg : args) {
                    if (arg instanceof File) {
                        File fileArg = (File) arg;
                        mtimes.put(fileArg, fileArg.lastModified());
                    }
                }
                Object invoke = method.invoke(delegate, args);
                // Compare the input file mtimes with the output files
                String baseName = baseName(method, methodMap);
                for (int i = 0; i < args.length; i++) {
                    Object arg = args[i];
                    if (arg instanceof File) {
                        File fileArg = (File) arg;
                        if (fileArg.lastModified() != mtimes.get(fileArg)) {
                            Files.copy(fileArg.toPath(), argFile(method, baseName, method.getParameters()[i], testDir).toPath());
                        }
                    }
                }
                return invoke;
            }
        );
    }

    public static CertManager replay(String testName, File parentDir) {
        File testDir = new File(parentDir, testName);
        testDir.mkdirs();
        Map<String, Integer> methodMap = new HashMap<>();
        return (CertManager) Proxy.newProxyInstance(CertManager.class.getClassLoader(), new Class[]{CertManager.class}, new InvocationHandler() {
            @Override
            public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
                String baseName = baseName(method, methodMap);
                for (int i = 0; i < args.length; i++) {
                    Object arg = args[i];
                    if (arg instanceof File) {
                        File file = argFile(method, baseName, method.getParameters()[i], testDir);
                        if (file.exists()) {
                            Files.copy(file.toPath(),
                                    ((File) arg).toPath(),
                                    StandardCopyOption.REPLACE_EXISTING);
                        }
                    }
                }
                return null;
            }
        });
    }

    public static CertManager replayAndRecord(String testName, Clock clock, File parentDir) {
        File testDir = new File(parentDir, testName);
        testDir.mkdirs();
        OpenSslCertManager delegate = new OpenSslCertManager(clock);
        Map<String, Integer> methodMap = new HashMap<>();
        return (CertManager) Proxy.newProxyInstance(CertManager.class.getClassLoader(), new Class[]{CertManager.class}, new InvocationHandler() {
            @Override
            public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
                final String baseName = baseName(method, methodMap);
                boolean existed = false;
                for (int i = 0; i < args.length; i++) {
                    Object arg = args[i];
                    if (arg instanceof File) {
                        File file = argFile(method, baseName, method.getParameters()[i], testDir);
                        if (file.exists()) {
                            Files.copy(file.toPath(),
                                    ((File) arg).toPath(),
                                    StandardCopyOption.REPLACE_EXISTING);
                            existed = true;
                        }
                    }
                }
                if (!existed) {
                    // Record the input files
                    Map<File, Long> mtimes = new HashMap<>();
                    for (Object arg : args) {
                        if (arg instanceof File) {
                            File fileArg = (File) arg;
                            mtimes.put(fileArg, fileArg.lastModified());
                        }
                    }
                    Object invoke = method.invoke(delegate, args);
                    // Compare the input file mtimes with the output files
                    for (int i = 0; i < args.length; i++) {
                        Object arg = args[i];
                        if (arg instanceof File) {
                            File fileArg = (File) arg;
                            if (fileArg.lastModified() != mtimes.get(fileArg)) {
                                Files.copy(fileArg.toPath(), argFile(method, baseName, method.getParameters()[i], testDir).toPath());
                            }
                        }
                    }
                    return invoke;
                }
                return null;
            }
        });
    }



}
